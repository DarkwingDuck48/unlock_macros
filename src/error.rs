//! Тип ошибок библиотеки.

/// Ошибка разбора или правки защиты VBA-проекта.
#[derive(Debug, thiserror::Error)]
pub enum Error {
    /// В потоке `PROJECT` не найдены строки `CMG`/`DPB`/`GC`.
    #[error("в файле нет строк CMG/DPB/GC (защита не найдена)")]
    NoProtection,
    /// Строка встречается не ровно один раз.
    #[error("строка {0} найдена {1} раз (ожидалась 1)")]
    LineCount(String, usize),
    /// Значение строки не является корректным hex.
    #[error("некорректный hex в значении строки")]
    BadHex,
    /// Encrypted Data Structure короче минимально необходимого.
    #[error("структура Encrypted Data Structure обрезана")]
    Truncated,
    /// Расшифрованная структура хеша пароля имеет неверный формат.
    #[error("структура хеша пароля повреждена")]
    BadHashStruct,
    /// Полезная нагрузка не помещается в требуемую длину.
    #[error("payload {payload} Б не влезает в {total} Б")]
    PayloadTooBig {
        /// Длина полезной нагрузки.
        payload: usize,
        /// Требуемая длина закодированного значения.
        total: usize,
    },
    /// Длина нового значения не совпала с длиной старого.
    #[error("новая строка имеет длину {new}, ожидалось {old}")]
    LengthMismatch {
        /// Ожидаемая (исходная) длина.
        old: usize,
        /// Фактическая длина нового значения.
        new: usize,
    },
    /// Пароль не представим в выбранной кодировке.
    #[error("пароль не представим в выбранной кодировке")]
    EncodingFailed,
    /// Файл не является ни OOXML, ни OLE.
    #[error("неизвестный формат файла (не OOXML и не OLE)")]
    UnknownFormat,
    /// В архиве отсутствует `vbaProject.bin`.
    #[error("в архиве нет vbaProject.bin")]
    NoVbaMember,
    /// Ошибка ввода-вывода.
    #[error("ошибка ввода-вывода: {0}")]
    Io(#[from] std::io::Error),
    /// Ошибка библиотеки `zip`.
    #[error("ошибка ZIP: {0}")]
    Zip(#[from] zip::result::ZipError),
}
